"""Matched perturbation-budget control with ordinary current-stroke optimization."""
import argparse
from pathlib import Path
from unittest.mock import patch

import numpy as np

from . import tt42_learning_course as course
from . import tt43_outgoing_generation as candidate
from .tt4_transfer_trial import _hash, _read, _write
from .tt43_outgoing_coverage import ROOT


def choose(quality, agreement, risks, supported, stock_quality, stock_risks):
    # Both conditions use the same hazard gate and private current-ball legal
    # rules. Only risk's weight in proposal generation and final order changes.
    valid = (agreement == 2) & supported & (quality < stock_quality - candidate.GAIN)
    return None if not valid.any() else int(np.argmin(np.where(valid, quality, np.inf)))


def run(args):
    digest = _hash(Path(__file__))
    if args.output.exists() and _read(args.output).get("ordinary_objective_sha256") != digest:
        raise ValueError("The recording was generated by a different control")

    def writer(path, doc):
        _write(path, doc | dict(ordinary_objective_sha256=digest))

    with patch.object(candidate, "RISK_WEIGHT", 0.0), patch.object(candidate, "choose", choose), patch.object(
        candidate, "_write", writer
    ):
        candidate.run(args)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bank", type=Path, default=ROOT / "outgoing-risk.json")
    parser.add_argument("--control", type=Path, default=course.ROOT / "no-more-practice.json.gz")
    parser.add_argument("--output", type=Path, default=ROOT / "outgoing-generation-ordinary.json.gz")
    parser.add_argument("--limit", default=2, type=int)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    run(args)
